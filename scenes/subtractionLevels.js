import {
  BLUE, PINK, YELLOW, ORANGE, INK,
} from "../components/theme.js?v=20260816b";

const COL_BIG   = BLUE;    // the 2-digit minuend (a)
const COL_SMALL = PINK;    // the 1-digit subtrahend (b)
const COL_TEN   = YELLOW;  // the literal "10"
const COL_NEED  = ORANGE;  // unknown / just-computed slot

// ---------- shared slot helpers ----------------------------------------

function subtractionSlots(round, answer = "?") {
  return {
    slots: [round.a, "-", round.b, "=", answer],
    colors: [COL_BIG, undefined, COL_SMALL, undefined, answer === "?" ? COL_NEED : undefined],
    reserve: [round.a, "-", round.b, "=", round.answer],
  };
}

// L7/L8 anchor (a - b = ?) — top of the persistent diagram.
function teenAnchorSlots(round, sumSlot) {
  return {
    slots: [round.a, "-", round.b, "=", sumSlot],
    colors: [COL_BIG, undefined, COL_SMALL, undefined, sumSlot === "?" ? COL_NEED : undefined],
    reserve: [round.a, "-", round.b, "=", round.answer],
  };
}

// L7/L8 split row: "? + ? - b = ?" — 7 slots. Slots 0 and 2 reveal to
// the two halves of a's decomposition (10 + ones). Slot 6 is the
// equation's answer; defaults to "?" but step-2 onAdvance passes the
// real answer so the trailing box gets filled alongside the anchor +
// result-row answer (per "答对了要填充").
//
// Default layout (L7, 破十法 in the ones place):
//   slot 0 = 10   (COL_TEN, the "whole" half that carries through)
//   slot 2 = ones (COL_NEED, the "subtracted-from" half)
//
// L8 opts in via { leftColor, rightColor } when slot 0 is the subtracted
// half and slot 2 is the whole one (L8 swaps the decomposition so the
// ones — the digit that stays whole in L8's 破十法 — is shown first):
//   L8 slot 0 = ones (COL_NEED)   L8 slot 2 = 10   (COL_TEN)
function teenSplitSlots(round, leftSlot = "□", rightSlot = "□", answerSlot = "?", opts = {}) {
  const leftColor = opts.leftColor ?? COL_TEN;
  const rightColor = opts.rightColor ?? COL_NEED;
  return {
    slots: [leftSlot, "+", rightSlot, "-", round.b, "=", answerSlot],
    colors: [
      leftColor, undefined, rightColor, undefined,
      COL_SMALL, undefined,
      answerSlot === "?" ? COL_NEED : undefined,
    ],
    // Reserve widest lifetime for stable slot centers across reveals.
    // ones is always 1-9 (single digit), but reserve to "10" so the
    // row layout doesn't reflow if pool math ever loosens.
    reserve: ["10", "+", "10", "-", round.b, "=", round.answer],
  };
}

// L7 result row: "10 + diff = ?" — 5 slots. Slot 2 (diff) is shown
// directly (audio states the diff in step 2); slot 4 is the answer
// box the kid picks. Col_TEN for the 10, COL_NEED for diff (stays
// after reveal), and answer slot cycles COL_NEED → INK on correct.
function l7ResultSlots(round, diff, answerSlot = "?") {
  return {
    slots: [10, "+", diff, "=", answerSlot],
    colors: [COL_TEN, undefined, COL_NEED, undefined, answerSlot === "?" ? COL_NEED : INK],
    reserve: [10, "+", "9", "=", round.answer],
  };
}

// L8 result row: "{ones} + sub = ?" — 5 slots. The 破十法 result row
// (vs L7's "10 + diff = ?") keeps the digit that stays whole in slot 0
// and the digit that gets subtracted-from in slot 2:
//   L7 (不退位, 破十法): slot 0 = 10, slot 2 = diff = ones - b.
//   L8 (退位,  破十法): slot 0 = ones, slot 2 = sub = 10 - b.
// So L8 carries "ones" through and subtracts b from the 10 instead of
// from ones. sub is computed in scene (sub = 10 - round.b); step 2 audio
// (l8-s2-{b}) asks the kid for it, then they pick it in the result row.
// See teenLinkPoints for the matching curve swaps (transform source
// split[0] → result[2] COL_TEN; carry split[2] → result[0] COL_NEED).
function l8ResultSlots(round, sub, answerSlot = "?") {
  return {
    slots: [round.ones, "+", sub, "=", answerSlot],
    colors: [COL_NEED, undefined, COL_NEED, undefined, answerSlot === "?" ? COL_NEED : INK],
    // ones ∈ [1, 8] (single digit, but reserve "9" for safety); sub
    // ∈ [1, 8] same. Answer ∈ [2, 9]. No literal "10" anywhere in
    // this row (unlike L7), so the reserve is narrower than L7's.
    reserve: ["9", "+", "9", "=", round.answer],
  };
}

// ---------- L7/L8 layout ------------------------------------------------

// 3 stacked rows — anchor (top) → split → result (bottom). 160px
// stride gives the ∧/∨ curves enough vertical runway without crowding
// the digits (size 60-80 boxes are ~60-80px tall).
const Y_ANCHOR = 240;
const Y_SPLIT  = 400;
const Y_RESULT = 580;

const ANCHOR_SIZE = 80;
const ROW_SIZE    = 60;

// Renders a single row into ctx[key]. Caller passes the slot layout and
// positioning opts; the function handles destroy + center-on-bar-x.
function renderTeenRow(ctx, key, slots, opts) {
  if (ctx[key]) ctx[key].destroy();
  ctx[key] = expression(ctx.k, {
    ...slots,
    // Centered on the step bar's x (LAYOUT.barX). ctx.arrowsRoot is
    // positioned at (0, 0) for the drawLink parent — using its pos.x
    // would shove the row off to the left edge (regression seen
    // 2026-08-16 in the L7 step-2 screenshot where the split row
    // clipped at x≈0).
    x: LAYOUT.barX,
    y: opts.y,
    size: opts.size,
  });
  return ctx[key];
}

// Returns the array of link points for the L7/L8 diagram. Four lines
// per level, both staying in the same shape across L7 and L8 (just
// with different "from" slots for the split→result arrow):
//   ∧ anchor[0] → split[0]   ("a splits into its ten-half")
//   ∧ anchor[0] → split[2]   ("a splits into its ones-half")
//   ∨ transform: split[transformFrom] → result[resultCenter]
//                L7: split[2]=ones → result[2]=diff
//                L8: split[0]=10   → result[2]=sub
//   ∨ subtrahend: split[4]=round.b → result[resultCenter]
//                "the b we're subtracting leads to the diff/sub"
// Per user feedback 2026-08-16 ("缺少第二行的3到第三行的□ 的线"),
// the subtrahend's connection to the result slot is what was missing.
// Earlier lines that have since been REMOVED:
//   - ∨ split[0] → result[0] (carry, "10 carries through"). User
//     feedback was that this looks redundant — the result row's
//     "10" reads fine on its own.
//   - ∨ anchor[1] → result[0] ("minus sign points to answer").
//     Same redundancy as the carry line.
//   - ∨ split[2] → result[0] (extra "ones → 10"). Pedagogically
//     weak — ones is what gets subtracted, not what becomes the 10.
//
// `resultCenter` (default 2) is the slot index of the sub value
// (diff for L7, sub for L8) in the result row — both at slot 2 of a
// 5-slot row.
//
// Bug fix (2026-08-16): the anchor is rendered via setAnchorEquation
// (roundScene) which stores the node on `ctx.anchorEqNode`, NOT on a
// `ctx.teenAnchorNode` key. The split / result rows ARE stored on
// `ctx.teenSplitNode` / `ctx.teenResultNode` (because renderTeenRow
// uses ctx[key] = expression(...) directly). So this helper has to
// look at `ctx.anchorEqNode` for the anchor and the `teen*` keys for
// the others — otherwise the ! anchor?.slotCenters guard returns
// early and no lines get drawn.
function teenLinkPoints(ctx, opts = {}) {
  const {
    resultCenter = 2,
    transformFrom = 2,
    transformColor = COL_NEED,
    splitLeftColor = COL_TEN,
    splitRightColor = COL_NEED,
  } = opts;
  const pts = [];
  const anchor = ctx.anchorEqNode;
  const split  = ctx.teenSplitNode;
  const result = ctx.teenResultNode;
  if (!anchor?.slotCenters) return pts;

  // ∧ anchor.a → split[0]. Color tracks whatever the slot actually
  // holds — L7 default is COL_TEN (split[0] = "10"); L8 swaps the
  // decomposition so split[0] holds "ones" and the line is COL_NEED.
  if (split?.slotCenters?.[0] != null && anchor.slotCenters[0] != null) {
    pts.push({
      from: { x: anchor.slotCenters[0], y: anchor.slotY + anchor.slotSizes[0] / 2 },
      to:   { x: split.slotCenters[0], y: split.slotY - split.slotSizes[0] / 2 },
      color: splitLeftColor,
      kind: "split",
    });
  }
  // ∧ anchor.a → split[2]. Color tracks the slot's content — L7
  // default is COL_NEED (split[2] = "ones"); L8 swaps so split[2]
  // holds "10" and the line is COL_TEN.
  if (split?.slotCenters?.[2] != null && anchor.slotCenters[0] != null) {
    pts.push({
      from: { x: anchor.slotCenters[0], y: anchor.slotY + anchor.slotSizes[0] / 2 },
      to:   { x: split.slotCenters[2], y: split.slotY - split.slotSizes[2] / 2 },
      color: splitRightColor,
      kind: "split",
    });
  }
  // ∨ transform: split[transformFrom] → result[resultCenter]. See the
  // block comment above for L7 vs L8 specifics.
  if (split?.slotCenters?.[transformFrom] != null && result?.slotCenters?.[resultCenter] != null) {
    pts.push({
      from: { x: split.slotCenters[transformFrom], y: split.slotY + split.slotSizes[transformFrom] / 2 },
      to:   { x: result.slotCenters[resultCenter], y: result.slotY - result.slotSizes[resultCenter] / 2 },
      color: transformColor,
      kind: "combine",
    });
  }
  // ∨ subtrahend: split[4]=round.b → result[resultCenter]. The b
  // we're subtracting leads to the diff/sub. Per user feedback
  // 2026-08-16: "缺少第二行的 3 到第三行的 □ 的线" — without this
  // arrow the kid can't see how the subtrahend connects to the
  // sub-result slot. Both L7 and L8 share this arrow (round.b lives
  // at split[4] in both layouts).
  if (split?.slotCenters?.[4] != null && result?.slotCenters?.[resultCenter] != null) {
    pts.push({
      from: { x: split.slotCenters[4], y: split.slotY + split.slotSizes[4] / 2 },
      to:   { x: result.slotCenters[resultCenter], y: result.slotY - result.slotSizes[resultCenter] / 2 },
      color: COL_SMALL,
      kind: "combine",
    });
  }

  return pts;
}

function redrawTeenLinks(ctx, opts = {}) {
  ctx.arrowNodes?.forEach((n) => n.destroy());
  ctx.arrowNodes = [];
  const pts = teenLinkPoints(ctx, opts);
  // Opacity bumped to 0.55 (was 0.4) — the COL_NEED ones-half line lands
  // as pale peach over cream at 0.4 and was hard to see; L4/L5 use 0.4 on
  // a tighter / darker backdrop so they got away with it. The COL_TEN
  // ten-half line still reads fine at 0.55. Match L4/L5's call shape too:
  // drawLink returns a single node, so spread is wrong (was silently no-op).
  for (const p of pts) {
    ctx.arrowNodes.push(drawLink(ctx.k, ctx.arrowsRoot, p.from, p.to, p.color, 7, 0.55));
  }
}

// ---------- shared audio chain helpers ---------------------------------

// Fires a per-step audio cue chain. Same pattern as L4/L5 (see
// scenes/level5.js::fireL5StepAudio): chain off the cheer chain's last
// cue when there's one (gap 400ms breath), otherwise play immediately
// with a small render-settle delay.
function fireTeenStepAudio(ctx, ids, _stepNumber, onComplete) {
  if (ctx.lastEncourageId) {
    window.PandaAudio.playAfter(ctx.lastEncourageId, ids, {
      gapMs: 400, seqGapMs: 40,
    }, onComplete);
    return;
  }
  window.PandaAudio.playSequence(ids, 40, 100, onComplete);
}

