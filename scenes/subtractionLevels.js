//          Step 2: pick the subtraction result (buttons bare single digits).
//            L7 ("个位相减"): diff = ones - b.  Result row "10 + diff = ?".
//            L8 ("十位相减"): sub  = 10 - b.   Result row "{ones} + sub = ?".
//          Step 3 ("合起来"): pick the final answer.
