// Same 3-row layout as L7 (per user "level8:也要像这样改造"), but the
// 凑十法 strategy is 破十法 (vs L7's also 破十法 in the ones place): the
// ten is subtracted from instead of the ones, since b > ones here.
//   1. Split a into 10 + ones (kid picks ones, step 1).
//   2. sub = 10 - b is asked via l8-s2-{b} audio ("十减 b 等于几"); the
//      result row "{ones} + sub = ?" appears with sub to be picked.
//   3. Answer = ones + sub is asked via l8-s3-{ones}-{b} audio
//      ("{ones} 加 {sub} 等于几"); kid picks the answer.
//
// ∨ curve roles (see teenLinkPoints for the math):
//   transform: split[2]=10 → result[2]=sub, COL_TEN  ("10 - b = sub")
//   subtrahend: split[4]=b → result[2]=sub, COL_SMALL  ("b connects to sub")

// L8 opts reused across all 3 step functions — the 破十法 swap (ones
// first, ten second in the split row) puts the ten at split[2] and
// the ones at split[0], so transformFrom flips from L7's 2 to 2 (no
// change at the index level, but the color track does). The ∧ lines
// also flip colors since split[0] now holds ones (COL_NEED) and
// split[2] holds 10 (COL_TEN).
const L8_SPLIT_COLORS = { leftColor: COL_NEED, rightColor: COL_TEN };
const L8_LINK_OPTS = {
  transformFrom: 2,
  transformColor: COL_TEN,
  splitLeftColor: COL_NEED,
  splitRightColor: COL_TEN,
};

const l8Steps = [
  // Step 1 — 拆 a. Split row order is "ones + 10 - b = ?" (swapped
  // from L7's "10 + ones - b = ?") so the digit that stays whole in
  // L8's 破十法 (ones) is shown first. Per user feedback 2026-08-16
  // ("第二步的顺序应该是 2+10-6").
  (ctx, round) => {
    ctx.setAnchorEquation(teenAnchorSlots(round, "?"), { y: Y_ANCHOR, size: ANCHOR_SIZE });
    fireTeenStepAudio(ctx, buildL8Step1Ids(round.a, round.b), 1, () => {
      renderTeenRow(ctx, "teenSplitNode", teenSplitSlots(round), { y: Y_SPLIT, size: ROW_SIZE });
      redrawTeenLinks(ctx, L8_LINK_OPTS);
    });
    return {
      question: {
        correct: round.ones,
        values: options(round.ones, { min: 1, max: 8 }),
        // Swapped from L7's "10+?" — matches the "ones + 10" split
        // row so the button shows the same shape as the slot it
        // fills. For ones=2 the kid sees "2+10" as the button label.
        labelFor: (v) => `${v}+10`,
      },
      onAdvance: () => {
        renderTeenRow(ctx, "teenSplitNode", teenSplitSlots(round, round.ones, 10, "?", L8_SPLIT_COLORS), { y: Y_SPLIT, size: ROW_SIZE });
        redrawTeenLinks(ctx, L8_LINK_OPTS);
      },
    };
  },

  // Step 2 — 十位相减. Anchor + split (revealed) stay. Result row
  // "{ones} + □ = ?" appears AFTER the l8-s2 audio asks for sub
  // ("十减 {b} 等于几"). Kid picks sub.
  (ctx, round) => {
    const sub = 10 - round.b;
    ctx.setAnchorEquation(teenAnchorSlots(round, "?"), { y: Y_ANCHOR, size: ANCHOR_SIZE });
    renderTeenRow(ctx, "teenSplitNode", teenSplitSlots(round, round.ones, 10, "?", L8_SPLIT_COLORS), { y: Y_SPLIT, size: ROW_SIZE });
    fireTeenStepAudio(ctx, buildL8Step2Ids(round.b), 2, () => {
      // Sub slot (slot 2) renders as "□" for the kid to land the
      // ten-place subtraction. Trailing answer slot stays a
      // COL_NEED placeholder until step 3.
      renderTeenRow(ctx, "teenResultNode", l8ResultSlots(round, "□"), { y: Y_RESULT, size: ROW_SIZE });
      redrawTeenLinks(ctx, L8_LINK_OPTS);
    });
    return {
      question: {
        correct: sub,
        // Sub range [1, 8]: b ∈ [2, 9], so sub = 10 - b ∈ [1, 8].
        // Bare single digits — the row reads "{ones} + □ = ?" and
        // the kid mentally reduces 10 - b to get sub.
        values: options(sub, { min: 1, max: 8 }),
      },
      onAdvance: () => {
        // Reveal sub in the result row (slot 2). The trailing "?"
        // (slot 4) stays a placeholder until step 3 picks the
        // answer.
        renderTeenRow(ctx, "teenResultNode", l8ResultSlots(round, sub), { y: Y_RESULT, size: ROW_SIZE });
        redrawTeenLinks(ctx, L8_LINK_OPTS);
      },
    };
  },

  // Step 3 — 合起来. Anchor + split + result-with-sub all stay from
  // step 2. The l8-s3 audio plays ("{ones} 加 {sub} 等于几"), then
  // the kid picks the final answer. Per user feedback 2026-08-16
  // "答对了要填充" still applies — once the answer is picked, every □
  // across the persistent diagram reveals to the value.
  (ctx, round) => {
    const sub = 10 - round.b;
    // Reorder options so the correct answer lands in position 3
    // (0-indexed 2). The default outward-walk order is
    // [correct, +1, -1, +2]; for 12-6 that gives [6, 7, 5, 8].
    // Per user feedback 2026-08-16 ("最后一步的选项应该是 5，7，6，8")
    // we want distractors sorted ascending with correct inserted at
    // index 2: [-1, +1, correct, +2] for 12-6 → [5, 7, 6, 8]. For
    // edge cases where correct already sits at position 3 (or the
    // distractors don't form a clean [-1, +1, +2] set), we leave
    // the outward-walk order alone — e.g. 11-9 (=2) yields
    // [3, 4, 2, 5] which is unusual but readable.
    const rawOpts = options(round.answer, { min: 2, max: 10 });
    const correctIdx = rawOpts.indexOf(round.answer);
    const orderedOpts =
      correctIdx !== 2 && rawOpts.length === 4
        ? (() => {
            const distractors = rawOpts.filter((v) => v !== round.answer)
              .sort((a, b) => a - b);
            return [...distractors.slice(0, 2), round.answer, ...distractors.slice(2)];
          })()
        : rawOpts;
    ctx.setAnchorEquation(teenAnchorSlots(round, "?"), { y: Y_ANCHOR, size: ANCHOR_SIZE });
    renderTeenRow(ctx, "teenSplitNode", teenSplitSlots(round, round.ones, 10, "?", L8_SPLIT_COLORS), { y: Y_SPLIT, size: ROW_SIZE });
    renderTeenRow(ctx, "teenResultNode", l8ResultSlots(round, sub), { y: Y_RESULT, size: ROW_SIZE });
    fireTeenStepAudio(ctx, buildL8Step3Ids(round.ones, round.b), 3, () => {
      // No new row appears — the kid looks at "{ones} + {sub} = ?"
      // and picks the final answer.
    });
    return {
      question: {
        correct: round.answer,
        // Answer range: [2, 9] for the borrow case (a ∈ [11,19],
        // b > ones → answer = ones + (10 - b) ∈ [2, 9]).
        values: orderedOpts,
        // Plain answer value on each button (NOT the decomposed
        // "{ones}+{sub}" form). Per user feedback 2026-08-16: "第
        // 三步都要出答案，你还给表达式". The decomposition lives in the
        // result row ("6 + sub = ?"); the buttons just need to be
        // the four candidate answers for the kid to scan and pick.
        labelFor: (v) => String(v),
      },
      onAdvance: () => {
        // Fill the anchor (slot 4), split row (slot 6), and result
        // row (slot 4) with the answer — per "答对了要填充".
        ctx.setAnchorEquation(teenAnchorSlots(round, round.answer), { y: Y_ANCHOR, size: ANCHOR_SIZE });
        renderTeenRow(ctx, "teenSplitNode", teenSplitSlots(round, round.ones, 10, round.answer, L8_SPLIT_COLORS), { y: Y_SPLIT, size: ROW_SIZE });
        renderTeenRow(ctx, "teenResultNode", l8ResultSlots(round, sub, round.answer), { y: Y_RESULT, size: ROW_SIZE });
        redrawTeenLinks(ctx, L8_LINK_OPTS);
        return new Promise((resolve) => {
          window.PandaAudio.playAfter(
            ctx.lastEncourageId,
            buildL8RewardIds(round.a, round.b, round.answer),
            { gapMs: 200, seqGapMs: 40 },
            resolve,
          );
        });
      },
    };
  },
];

