//
//        Both L7 and L8 use 破十法 (subtract where it fits, keep the
//        other half whole): L7 borrows from ones (b ≤ ones), L8 borrows
//        from 10 (b > ones). Same conceptual strategy, mirrored.
//
// Audio cues (composite, generated by tools/build-audio-tencent.mjs):
//   l6-s1-{a}-{b}                  "{a}减{b}等于几"
//   l6-rwd-{a}-{b}-{answer}        "{a}减{b}等于{answer}"
//   l7-s1-{a}-{b}                  "{a}减{b}等于几，我们先把{a}拆成十加几"
//   l7-s2q-{ones}-{b}              "个位相减{ones}减{b}等于几"   (asks for diff)
//   l7-s2-{ones}-{b}               "个位相减{ones}减{b}等于{diff}" (legacy; states diff)
//   l7-s3-{diff}                   "十加{diff}等于几"
//   l7-rwd-{a}-{b}-{answer}        "{a}减{b}等于{answer}"
//   l8-s1-{a}-{b}                  "{a}减{b}等于几，我们先把{a}拆成十加几"
//   l8-s2-{b}                      "十减{b}等于几"               (asks for sub)
//   l8-s3-{ones}-{b}               "{ones}加{10-b}等于几"        (asks for answer)
//   l8-rwd-{a}-{b}-{answer}        "{a}减{b}等于{answer}"

